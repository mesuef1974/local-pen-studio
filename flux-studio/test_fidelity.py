import base64
import io
import unittest
import cv2
import numpy as np
from PIL import Image
from faithful_paths import extract
from path_fidelity import audit,webgpu_target,validate_paths


def encoded(array):
    stream=io.BytesIO();Image.fromarray(array).save(stream,format='PNG')
    return 'data:image/png;base64,'+base64.b64encode(stream.getvalue()).decode()


def settings(array,pen=.15):
    return dict(image=encoded(array),mmPerPixel=.2,penMm=pen,inkThreshold=0)


class FidelityTests(unittest.TestCase):
    def test_filled_shapes_and_white_hole_survive_physical_pen_reconstruction(self):
        image=np.full((110,110),255,np.uint8)
        cv2.rectangle(image,(20,20),(85,85),0,-1);cv2.rectangle(image,(35,35),(70,70),255,-1)
        data=settings(image);result=extract(data);score=result['fidelity']
        self.assertGreater(score['inkIoU'],90)
        self.assertGreater(score['inkIoU'],score['baselineCenterline']['inkIoU']+40)
        validate_paths(result['paths'],110,110)
        again=audit(data|{'paths':result['paths']})
        self.assertEqual(score['inkIoU'],again['inkIoU'])
        raster=np.asarray(Image.open(io.BytesIO(base64.b64decode(again['reconstruction'].split(',')[1]))))
        self.assertGreater(int(raster[50,50]),245,'never bridge across the white hole')

    def test_isolated_dots_are_not_silently_discarded(self):
        image=np.full((60,80),255,np.uint8);image[20,20]=0;image[40,60]=0
        result=extract(settings(image))
        self.assertEqual(result['isolatedMarksPreserved'],2)
        self.assertGreaterEqual(len(result['paths']),2)
        self.assertGreater(result['fidelity']['inkRecall'],30)

    def test_pen_diameter_changes_the_geometry_and_not_only_svg_styling(self):
        image=np.full((80,100),255,np.uint8);cv2.rectangle(image,(10,10),(40,60),0,-1)
        thin=extract(settings(image,.15));wide=extract(settings(image,.4))
        self.assertNotEqual(thin['paths'],wide['paths'])
        self.assertGreater(sum(len(p) for p in thin['paths']),sum(len(p) for p in wide['paths']))

    def test_solid_ink_and_bad_physics_are_rejected_explicitly(self):
        with self.assertRaises(ValueError):extract(settings(np.zeros((40,40),np.uint8)))
        image=np.full((40,40),255,np.uint8)
        for value in (True,float('nan'),0,100):
            with self.subTest(value=value),self.assertRaises(ValueError):extract(settings(image)|{'mmPerPixel':value})

    def test_audit_detects_exclusions_and_ink_outside_image(self):
        image=np.full((40,40),255,np.uint8);cv2.line(image,(0,0),(0,30),0,1)
        data=settings(image,.4)
        full=audit(data|{'paths':[[[0,0],[0,30]]]})
        empty=audit(data|{'paths':[]})
        self.assertEqual(empty['inkIoU'],0)
        self.assertGreater(full['extraInkPercent'],0)
        self.assertTrue(full['auditIncludesOutsideImage'])

    def test_colored_source_is_identified_and_not_claimed_as_color_match(self):
        image=np.full((40,40,3),255,np.uint8);image[15:25,15:25]=[255,0,0]
        result=audit(settings(image)|{'paths':[]})
        self.assertGreater(result['coloredPixelsPercent'],0)
        self.assertIn('not identity',result['scope'])

    def test_adversarial_coordinates_and_complexity_are_bounded(self):
        for paths in ([[[float('nan'),0],[1,1]]],[[[-.6,0],[1,1]]],[[[1,1]]],[[[0,0],[1,1]]]*10001):
            with self.subTest(paths=str(paths)[:50]),self.assertRaises(ValueError):validate_paths(paths,40,40)
        for count in (6000,6001,10000):
            validate_paths([[[0,0],[1,1]]]*count,40,40)
        isolated=np.full((180,180),255,np.uint8);isolated[::2,::2]=0
        with self.assertRaisesRegex(ValueError,'التعقيد'):extract(settings(isolated))
        from path_fidelity import render_svg
        with self.assertRaisesRegex(ValueError,'الآمنة'):render_svg([],100,100,12000)

    def test_crossings_and_empty_input_do_not_add_white_bridges(self):
        image=np.full((80,80),255,np.uint8);cv2.line(image,(10,10),(65,65),0,2);cv2.line(image,(65,10),(10,65),0,2)
        result=extract(settings(image));self.assertGreater(result['fidelity']['inkRecall'],50)
        empty=extract(settings(np.full((40,40),255,np.uint8)))
        self.assertEqual(empty['paths'],[]);self.assertEqual(empty['fidelity']['inkIoU'],100)

    def test_tone_comparison_does_not_invent_gray_bands_by_upscaling_reference(self):
        image=np.full((40,40),255,np.uint8);cv2.line(image,(5,5),(30,30),0,1)
        data=settings(image);paths=[[[5,5],[30,30]]]
        initial=audit(data|{'paths':paths})
        # A raster generated by these exact paths must have zero native tone error.
        repeated=audit(data|{'image':initial['reconstruction'],'paths':paths})
        self.assertEqual(repeated['grayErrorInkRegion'],0)

    def test_webgpu_reference_mask_matches_cairo_audit_dimensions_and_counts(self):
        image=np.full((60,75),255,np.uint8);cv2.line(image,(8,10),(62,49),0,3)
        data=settings(image);paths=[[[8,10],[62,49]]]
        target=webgpu_target(data|{'paths':paths})
        full=audit(data|{'paths':paths})
        packed=np.frombuffer(base64.b64decode(target['bitsBase64']),dtype=np.uint8)
        bits=np.unpackbits(packed,bitorder='little')[:target['width']*target['height']]
        expected_dims=((75+6)*full['auditUpscale'],(60+6)*full['auditUpscale'])
        self.assertEqual((target['width'],target['height']),expected_dims)
        self.assertEqual(int(bits.sum()),target['expected'])
        self.assertEqual(target['auditUpscale'],full['auditUpscale'])

    def test_server_routes_new_and_legacy_paths_without_mutating_reference(self):
        import importlib.util
        from pathlib import Path
        spec=importlib.util.spec_from_file_location('flux_server_under_test',Path(__file__).with_name('server.py'))
        server=importlib.util.module_from_spec(spec);spec.loader.exec_module(server)
        process=server.process
        image=np.full((60,60),255,np.uint8);cv2.line(image,(10,10),(45,40),0,3)
        data=settings(image);original=data['image']
        result=process('/api/paths',data|{'lineMode':'faithful'})
        self.assertIn('fidelity',result);self.assertEqual(data['image'],original)
        check=process('/api/path-audit',data|{'paths':result['paths']})
        self.assertEqual(check['inkIoU'],result['fidelity']['inkIoU'])
        target=process('/api/path-audit-target',data)
        self.assertEqual(target['expected'],int(np.count_nonzero(np.unpackbits(np.frombuffer(base64.b64decode(target['bitsBase64']),dtype=np.uint8),bitorder='little')[:target['width']*target['height']])))
        legacy=process('/api/paths',data|{'lineMode':'centerline','minLength':2,'tolerance':0})
        self.assertIn('paths',legacy);self.assertNotIn('fidelity',legacy)
        for retired in ['/api/model','/api/post']:
            with self.assertRaises(ValueError):process(retired,{})

